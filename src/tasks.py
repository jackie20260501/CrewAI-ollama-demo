from crewai import Task


def create_research_task(agent) -> Task:
    return Task(
        description=(
            "研究 AI 在 2026 年的最新发展趋势，找出 3 个最重要的方向。"
            "必须使用中文输出，不要使用英文标题。"
            "请只基于通用技术趋势进行总结，不要编造具体新闻、公司数据或来源。"
            "对于缺少可验证证据或仍处于早期阶段的方向，请使用谨慎表达，避免写成确定会发生。"
            "不要把量子计算描述为 2026 年一定会给 AI 带来重大突破，只能说明它是值得关注的长期方向。"
        ),
        expected_output=(
            "一份全中文简短研究报告，包含 3 个核心趋势。"
            "每个趋势包含中文标题和 2-3 句话解释。"
            "不要出现英文标题，不要编造具体新闻、公司数据或来源。"
        ),
        agent=agent,
    )


def create_writing_task(agent, context) -> Task:
    return Task(
        description=(
            "根据研究报告，写一篇 180-220 个中文字的中文博客短文。"
            "必须分为 3 段，不要超过 220 个中文字。"
            "不要使用英文标题。"
            "对尚不确定的技术趋势要使用谨慎表达，不要夸大。"
        ),
        expected_output=(
            "一篇 180-220 个中文字、分为 3 段、结构清晰、语言自然的中文短文。"
            "不要超过 220 个中文字，不要使用英文标题。"
        ),
        agent=agent,
        context=context,
    )


def create_review_task(agent, context) -> Task:
    return Task(
        description=(
            "审阅作家写出的中文短文，检查事实是否准确、结构是否清晰、语言是否自然，"
            "并给出最终优化版本。"
            "你必须真正重写和优化文章，不能只重复原文、不能只做轻微替换、不能保留你自己指出需要修改的问题。"
            "最终版本必须保持 180-220 个中文字、分为 3 段、不要超过 220 个中文字。"
            "如果原文有夸大或缺少证据的说法，请改成更谨慎的表达。"
            "请先在心里识别原文中至少 3 个需要修改的点，然后把这些修改实际写入最终版本。"
            "最终版本必须比原文更短、更谨慎、更像中文短文。"
        ),
        expected_output=(
            "先输出“最终优化版本：”，下面给出已经重写后的 180-220 个中文字中文短文。"
            "最终版本必须体现你的修改，不能只是复制原文。"
            "如果审稿意见中指出了某个问题，最终优化版本里必须已经修正该问题。"
            "不要在最终版本中保留“更深层次的技术突破”“成为主流”“重大进展”等过强表达，除非改成更谨慎的说法。"
            "然后输出“审稿意见：”，列出 3 条以内简短审稿意见。"
        ),
        agent=agent,
        context=context,
    )
